#!/usr/bin/env node
// Regenerates docs/api/endpoints.md from the NestJS controllers in backend/src.
// Usage (from the repository root): node scripts/generate-endpoints-doc.js
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'backend', 'src');
const OUT = path.join(ROOT, 'docs', 'api', 'endpoints.md');

const files = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (name.endsWith('.controller.ts')) files.push(p);
  }
})(SRC);

const controllers = [];
for (const file of files.sort()) {
  const src = fs.readFileSync(file, 'utf8');
  const head = src.split(/export class/)[0];
  const ctrl = head.match(/@Controller\(\s*(?:'([^']*)'|"([^"]*)")?\s*\)/);
  const prefix = ctrl ? (ctrl[1] ?? ctrl[2] ?? '') : '';
  const classRoles = (head.match(/@Roles\(([^)]*)\)/) || [])[1];
  const classPublic = /@Public\(\)/.test(head);
  const lines = src.split('\n');
  const routes = [];
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/@(Get|Post|Put|Patch|Delete)\(\s*(?:'([^']*)'|"([^"]*)")?\s*\)/);
    if (!m) continue;
    // All decorators of this handler: the block of @-lines around the route decorator
    const deco = [lines[i]];
    for (let j = i - 1; j >= 0 && /^\s*@/.test(lines[j]); j--) deco.push(lines[j]);
    for (let k = i + 1; k < lines.length && /^\s*@/.test(lines[k]); k++) deco.push(lines[k]);
    const d = deco.join(' ');
    const roles = (d.match(/@Roles\(([^)]*)\)/) || [])[1] ?? classRoles;
    const access = /@Public\(\)/.test(d) || classPublic
      ? 'Public'
      : roles ? roles.replace(/Role\./g, '').replace(/\s+/g, ' ').trim() : 'Signed in';
    const summary = (d.match(/summary:\s*'([^']*)'/) || [])[1] ?? '';
    const route = ['api', prefix, m[2] ?? m[3] ?? ''].filter(Boolean).join('/').replace(/\/+/g, '/');
    routes.push({ method: m[1].toUpperCase(), path: `/${route}`, access, summary });
  }
  if (routes.length) {
    controllers.push({
      name: path.basename(file, '.controller.ts'),
      file: path.relative(ROOT, file).replace(/\\/g, '/'),
      routes,
    });
  }
}

const total = controllers.reduce((n, c) => n + c.routes.length, 0);
const esc = (s) => s.replace(/\|/g, '\\|');
let md = `# API Endpoints

<!-- Generated by scripts/generate-endpoints-doc.js — do not edit by hand. -->

${total} routes in ${controllers.length} controllers. Regenerate after changing a controller:

\`\`\`bash
node scripts/generate-endpoints-doc.js
\`\`\`

## Conventions

- **Base URL:** \`https://novabulletin-api.onrender.com/api\` in production, \`http://localhost:4000/api\` locally.
- **Authentication:** \`Authorization: Bearer <access token>\` from \`POST /api/auth/login\`. Refresh with \`POST /api/auth/refresh\`. Every route needs a valid token unless marked **Public**.
- **Access** column: the roles allowed (\`@Roles\`). "Signed in" means any authenticated user; services still restrict data to the caller's institution, classes or children.
- **Success response:** \`{ "success": true, "data": …, "timestamp": "…" }\`.
- **Error response:** \`{ "success": false, "statusCode": 403, "error": "Forbidden", "message": "…", "path": "…", "timestamp": "…" }\`. Messages are usually in French, ready to show to the user.
- **Rate limit:** 100 requests per minute per client.
- **Interactive docs:** Swagger UI at \`/api/docs\` when \`NODE_ENV\` is not \`production\`.

## Index

${controllers.map((c) => `[${c.name}](#${c.name})`).join(' · ')}
`;
for (const c of controllers) {
  md += `\n## ${c.name}\n\nSource: \`${c.file}\`\n\n| Method | Path | Access | Description |\n|---|---|---|---|\n`;
  for (const r of c.routes) md += `| ${r.method} | \`${r.path}\` | ${esc(r.access)} | ${esc(r.summary)} |\n`;
}
fs.writeFileSync(OUT, md);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${total} routes, ${controllers.length} controllers`);
